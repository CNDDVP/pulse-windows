/** 语言白名单与后端 AppSettings.language 校验（src-tauri/src/types.rs）一致：非 en 一律回落 zh。 */
export function normalizeLang(v: unknown): Lang {
  return v === "en" ? "en" : "zh";
}

/** BCP 47 tag：zh 用 zh-CN（简体中文），en 用 en。 */
export function documentLang(lang: Lang): string {
  return lang === "en" ? "en" : "zh-CN";
}

export function applyDocumentLang(lang: Lang): void {
  if (typeof document !== "undefined") document.documentElement.lang = documentLang(lang);
}

