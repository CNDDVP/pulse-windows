/** 插值：{name} 占位符；vars 缺该占位符时保留 {name} 原文，绝不静默吞掉。 */
function interpolate(raw: string, vars?: TVars): string {
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** 纯函数版本：给定语言翻译。en 缺 key 回退 zh；两边都缺返回 key 本身。 */
export function translate(lang: Lang, key: string, vars?: TVars): string {
  const raw = dictionaries[lang][key] ?? dictionaries.zh[key];
  return raw === undefined ? key : interpolate(raw, vars);
}

// 模块级当前语言：非 React 场景（及未包 Provider 的旧测试）共用，默认 zh。
let currentLang: Lang = "zh";

export function getLang(): Lang {
  return currentLang;
}

/** 设置模块级语言并同步 <html lang>。Provider 内部也经此同步，保持两条通道一致。 */
export function setLang(lang: Lang): void {
  currentLang = normalizeLang(lang);
  applyDocumentLang(currentLang);
}

/** 便捷入口：读模块级当前语言。组件内请用 useLang().t（随 Provider 重渲染）。 */
export function t(key: string, vars?: TVars): string {
  return translate(currentLang, key, vars);
}

// ---------------------------------------------------------------------------
// React 层：I18nProvider + useLang
// ---------------------------------------------------------------------------

interface I18nContextValue {
  lang: Lang;
  /** 仅在无设置通道可走时使用（测试/独立窗口）；应用内语言切换走既有设置持久化。 */
  setLang: (lang: Lang) => void;
  /** 绑定当前 context 语言：语言切换触发重渲染后取值随之更新。 */
  t: (key: string, vars?: TVars) => string;
}

/** 无 Provider 时的兜底：等价于模块级 zh（与历史行为一致，旧测试无需逐个包 Provider）。 */
const fallbackValue: I18nContextValue = { lang: "zh", setLang: (l) => setLang(l), t: (key, vars) => translate(getLang(), key, vars) };

const I18nContext = createContext<I18nContextValue>(fallbackValue);

/**
 * lang 传法（受控）：App 每个窗口根把 settings 派生的语言传进来
 * （`lang={normalizeLang(settings?.language)}`），语言设置走既有设置通道
 * （update_settings → settings-updated 事件 → 各窗口 settings → Provider）。
 * 不传 lang 时退化为本地 state（供测试/独立使用）。
 */
export function I18nProvider({ lang, onLangChange, children }: { lang?: Lang; onLangChange?: (lang: Lang) => void; children: ReactNode }) {
  // 传 lang 即完全受控：直接以 normalize 后的 prop 为准，不镜像到内部 state
  // （避免「effect 里同步 props→state」的级联渲染）；不传时退化为本地 state（测试/独立使用）。
  const [local, setLocal] = useState<Lang>("zh");
  const controlled = lang !== undefined ? normalizeLang(lang) : undefined;
  const effective = controlled ?? local;
  const change = useCallback(
    (next: Lang) => {
      const v = normalizeLang(next);
      if (controlled === undefined) setLocal(v);
      onLangChange?.(v);
    },
    [controlled, onLangChange],
  );
  // 同步模块级语言与 <html lang>（副作用统一收敛在 setLang）。
  useEffect(() => {
    setLang(effective);
  }, [effective]);
  const bound = useCallback((key: string, vars?: TVars) => translate(effective, key, vars), [effective]);
  // 文件名是 i18n.ts（词典/纯函数/Provider 同处一文件），故用 createElement 而非 JSX 语法。
  return createElement(I18nContext.Provider, { value: { lang: effective, setLang: change, t: bound } }, children);
}

export function useLang(): I18nContextValue {
  return useContext(I18nContext);
}
